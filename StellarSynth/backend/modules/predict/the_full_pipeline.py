class AthenaCTGRU(nn.Module):
    def __init__(
        self,
        input_dim: int = 13,
        hidden_dim: int = 128,
        static_dim: int = 3,
        mlp_dim1: int = 64,
        mlp_dim2: int = 32,
        dropout: float = 0.2,
    ):
        super().__init__()
        self.hidden_dim = hidden_dim
        self.decay_w = nn.Linear(1, hidden_dim)
        self.gru_cell = nn.GRUCell(input_dim, hidden_dim)

        self.mlp = nn.Sequential(
            nn.Linear(hidden_dim + static_dim, mlp_dim1),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(mlp_dim1, mlp_dim2),
            nn.GELU(),
            nn.Linear(mlp_dim2, 2),
        )

    def forward(self, x_dyn, x_stat, x_mask):
        B, T, _ = x_dyn.shape
        dev = x_dyn.device

        h = torch.zeros(B, self.hidden_dim, device=dev)
        delta_t = torch.zeros(B, 1, device=dev)

        for t in range(T):
            x_t = x_dyn[:, t, :]
            m_t = x_mask[:, t, :]

            if t > 0:
                jolt_w = (m_t * x_mask[:, t - 1, :]).squeeze(-1)
            else:
                jolt_w = m_t.squeeze(-1)

            scale = torch.ones(B, 13, device=dev)
            scale[:, 11] = jolt_w
            x_t = x_t * scale

            delta_t = delta_t + 0.2

            decay_arg = F.relu(self.decay_w(delta_t))
            gamma = torch.exp(-decay_arg)
            h_decayed = h * gamma

            h_new = self.gru_cell(x_t, h_decayed)
            h = m_t * h_new + (1.0 - m_t) * h_decayed
            delta_t = delta_t * (1.0 - m_t)

        z = torch.cat([h, x_stat], dim=-1)
        return self.mlp(z)

