def get_solar_cycle_phase(date_str):
    try:
        dt = pd.to_datetime(date_str).to_pydatetime()
        c24_start, c24_end = datetime(2008, 12, 1), datetime(2019, 12, 1)
        c25_start, c25_end = datetime(2019, 12, 1), datetime(2030, 12, 1)
        if c24_start <= dt < c24_end:
            return float((dt - c24_start).total_seconds() / (c24_end - c24_start).total_seconds())
        elif dt >= c25_start:
            return float((dt - c25_start).total_seconds() / (c25_end - c25_start).total_seconds())
        return 0.5
    except:
        return 0.0

def parse_tai_string(t_str):
    try:
        parts = t_str.split('_')
        return datetime.strptime(parts[0] + "_" + parts[1], "%Y%m%d_%H%M%S")
    except (ValueError, IndexError):
        return None

def compute_potential_field_cea(br, dx, dy):
    ny, nx = br.shape
    if nx * ny == 0:
        return None, None
    kx = 2.0 * np.pi * np.fft.fftfreq(nx).reshape(1, -1) / dx
    ky = 2.0 * np.pi * np.fft.fftfreq(ny).reshape(-1, 1) / dy
    k = np.sqrt(kx**2 + ky**2)
    k[0, 0] = 1.0
    br_hat = np.fft.fft2(br)
    bx_pot = np.real(np.fft.ifft2(-1j * (kx / k) * br_hat))
    by_pot = np.real(np.fft.ifft2(-1j * (ky / k) * br_hat))
    return bx_pot, by_pot

def extract_hed_features_cea(br, bt, bp, scales):
    dx, dy, da = scales
    bx_obs = -bp
    by_obs = -bt
    bz_obs = br

    bx_pot, by_pot = compute_potential_field_cea(br, dx, dy)
    if bx_pot is None:
        return np.zeros(14), 0.0

    rho = ((bx_obs - bx_pot)**2 + (by_obs - by_pot)**2) / (8.0 * np.pi)

    mask = rho > 5000.0
    used_fallback = 0.0
    if np.sum(mask) < 10:
        mask = rho > np.percentile(rho, 99)
        used_fallback = 1.0

    bh_obs = np.sqrt(bx_obs**2 + by_obs**2)
    curl_z = np.gradient(by_obs, axis=1) / dx - np.gradient(bx_obs, axis=0) / dy
    curl_z_SI = curl_z * 100.0
    mu0_SI = 4.0 * np.pi * 1e-7
    jz_Am2 = (curl_z * 1e-2) / mu0_SI

    vec = np.zeros(14)
    m_sum = np.sum(mask)

    if m_sum > 0:
        vec[0] = np.sum(rho[mask]) * da
        vec[1] = np.sum(np.abs(bz_obs[mask])) * da
        vec[2] = np.sum(np.abs(jz_Am2[mask])) * da * 1e-4
        vec[3] = np.mean(np.abs(jz_Am2[mask]))

        hc_SI = bz_obs * curl_z_SI
        vec[4] = np.sum(np.abs(hc_SI[mask])) * da * 1e-4
        vec[5] = np.mean(np.abs(hc_SI[mask]))
        vec[6] = np.sum(hc_SI[mask]) * da * 1e-4

        sum_bz2 = np.sum(bz_obs[mask]**2)
        if sum_bz2 > 0:
            vec[7] = (np.sum(curl_z[mask] * bz_obs[mask]) / sum_bz2) * 1e8

        bh_pot = np.sqrt(bx_pot**2 + by_pot**2)
        dot_h = bx_obs * bx_pot + by_obs * by_pot
        mag_h = bh_obs * bh_pot
        shear_mask = mask & (bh_obs > 10.0)
        if np.sum(shear_mask) > 0:
            vec[8] = np.mean(np.arccos(np.clip(np.abs(dot_h[shear_mask]) / (mag_h[shear_mask] + 1e-6), 0.0, 1.0)))

        grad_bh_x = np.gradient(bh_obs, axis=1) / dx * 100.0
        grad_bh_y = np.gradient(bh_obs, axis=0) / dy * 100.0
        vec[9] = np.mean(np.sqrt(grad_bh_x**2 + grad_bh_y**2)[mask])
        vec[10] = m_sum * da

        lbl, n_islands = label(mask, connectivity=2, return_num=True)
        chi = euler_number(mask, connectivity=2)
        beta_0 = n_islands
        beta_1 = max(beta_0 - chi, 0)
        norm_area = vec[10] / 1e18
        if norm_area > 0.001:
            vec[12] = (beta_0 + beta_1) / norm_area

        vec[13] = used_fallback

    return vec, vec[6]

def build_file_map(local_folder_path):
    file_map = {}
    for f in glob.glob(os.path.join(local_folder_path, "*.fits")):
        base = os.path.basename(f)
        parts = base.split('.')
        if len(parts) >= 3 and 'TAI' in base:
            t_str, comp = parts[-3], parts[-2]
            file_map.setdefault(t_str, {})[comp] = f
    return file_map

def process_live_harp(harp_dir):
    file_map = build_file_map(harp_dir)
    raw_timestamps = sorted([ts for ts in file_map.keys() if parse_tai_string(ts) is not None])

    if not raw_timestamps:
        return None

    # Isolate the most recent timestamps required to fulfill the SEQUENCE_LENGTH
    # Assuming the data acquisition downloaded excess history (e.g., 180 frames).
    aligned_timestamps = []
    current_dt = parse_tai_string(raw_timestamps[-1])

    for i in range(SEQUENCE_LENGTH - 1, -1, -1):
        target_dt = current_dt - pd.Timedelta(minutes=CADENCE_MINS * i)
        # Find closest match within a 6-minute tolerance
        closest_ts = None
        min_diff = float('inf')
        for ts in raw_timestamps:
            dt = parse_tai_string(ts)
            diff = abs((dt - target_dt).total_seconds())
            if diff <= 360 and diff < min_diff:
                closest_ts = ts
                min_diff = diff
        aligned_timestamps.append(closest_ts)

    # Extract Static Features from the most recent valid frame
    valid_ts = [ts for ts in aligned_timestamps if ts is not None]
    if not valid_ts: return None

    ref_f = file_map[valid_ts[-1]].get('Br')
    if not ref_f: return None

    with fits.open(ref_f) as h:
        h0 = h[1].header #if len(h) > 1 else h[0].header
        rsun_cm = h0.get('RSUN_REF', 6.96e8) * 100.0
        dx = h0.get('CDELT1', 0.03) * (np.pi / 180.0) * rsun_cm
        dy, da = dx, dx * dx
        scales = (dx, dy, da)


            # h0      = h[1].header
            # rsun_cm = h0.get('RSUN_REF', 6.96e8) * 100.0
            # cdelt   = h0.get('CDELT1', 0.03)
            # dx      = cdelt * (np.pi / 180.0) * rsun_cm
            # dy      = dx
            # da      = dx * dy
            # scales  = (dx, dy, da)


        lon_rad = h0.get('CRVAL1', 0.0) * (np.pi / 180.0)
        lat_rad = h0.get('CRVAL2', 0.0) * (np.pi / 180.0)
        static_vec = [float(np.sin(lon_rad) * np.cos(lat_rad)), float(np.sin(lat_rad)), get_solar_cycle_phase(str(h0.get('DATE-OBS')))]

    history, h_buffer, mask_history = [], [], []

    for ts in aligned_timestamps:
        if ts is None or 'Br' not in file_map[ts] or 'Bt' not in file_map[ts] or 'Bp' not in file_map[ts]:
            # Impute missing frames (Forward Fill)
            if history:
                new_vec = history[-1].copy()
                new_vec[11] = 0.0
                history.append(new_vec)
                h_buffer.append(h_buffer[-1])
            else:
                history.append(np.zeros(14))
                h_buffer.append(0.0)
            mask_history.append(0.0)
            continue

        try:
            br = np.nan_to_num(fits.getdata(file_map[ts]['Br'], 1))
            bt = np.nan_to_num(fits.getdata(file_map[ts]['Bt'], 1))
            bp = np.nan_to_num(fits.getdata(file_map[ts]['Bp'], 1))

            vec, h_val = extract_hed_features_cea(br, bt, bp, scales)
            del br, bt, bp

            # Compute Jolt
            if len(h_buffer) >= 2 and mask_history[-1] == 1.0 and mask_history[-2] == 1.0:
                vec[11] = (h_val - 2 * h_buffer[-1] + h_buffer[-2]) / (720.0 ** 2)
            else:
                vec[11] = 0.0

            history.append(vec)
            h_buffer.append(h_val)
            mask_history.append(1.0)
        except Exception as e:
            print(f"Physics engine failure for {ts}: {e}")
            if history:
                history.append(history[-1].copy())
                h_buffer.append(h_buffer[-1])
            else:
                history.append(np.zeros(14))
                h_buffer.append(0.0)
            mask_history.append(0.0)

    X_seq = np.expand_dims(np.array(history, dtype=np.float32), axis=0)
    X_static = np.expand_dims(np.array(static_vec, dtype=np.float32), axis=0)
    X_mask = np.expand_dims(np.array(mask_history, dtype=np.float32).reshape(-1, 1), axis=0)


    return X_seq, X_static, X_mask
