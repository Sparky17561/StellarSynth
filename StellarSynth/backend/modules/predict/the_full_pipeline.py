import os
import json
import numpy as np

# Configuration
STATS_FILE_PATH = "normalization_stats.json"

def load_normalization_stats(filepath):
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Normalization stats file not found at: {filepath}")
    with open(filepath, 'r') as f:
        return json.load(f)

def apply_normalization(X_seq, stats):
    """
    Applies static normalization parameters to the input tensor.
    Expects X_seq shape: (batch_size, sequence_length, 14)
    """
    X_norm = np.copy(X_seq)

    for key, s in stats["features"].items():
        ch = int(key.split("_")[0])

        # Skip vec[13] (Fallback) as it is dropped at the end
        if ch == 13:
            continue

        strategy = s["strategy"]
        col = X_norm[:, :, ch]

        if strategy == "log10_zscore":
            col = np.maximum(col, s["physical_floor"])
            col = np.log10(col)
            X_norm[:, :, ch] = (col - s["log10_mean"]) / s["log10_std"]

        elif strategy == "log1p_robust":
            col = np.log1p(np.maximum(col, 0.0))
            X_norm[:, :, ch] = (col - s["log1p_median"]) / s["log1p_iqr"]

        elif strategy == "zscore":
            X_norm[:, :, ch] = (col - s["mean"]) / s["std"]

        elif strategy == "clip_zscore":
            col = np.clip(col, -s["clip_bound_abs"], s["clip_bound_abs"])
            X_norm[:, :, ch] = (col - s["mean_post_clip"]) / s["std_post_clip"]

        elif strategy == "none":
            pass

    # Drop vec[13] (Fallback flag) -> new shape (batch_size, sequence_length, 13)
    X_norm = np.delete(X_norm, 13, axis=2)

    # Assert no invalid values generated during transform
    if np.isnan(X_norm).any() or np.isinf(X_norm).any():
        raise ValueError("Normalization produced NaN or Inf values.")

    return X_norm.astype(np.float32)

def process_inference_tensors(inference_tensors, stats_filepath=STATS_FILE_PATH):
    """
    Driver function to normalize a dictionary of active HARP tensors.
    inference_tensors format: {harpnum: (X_seq, X_static, X_mask)}
    """
    stats = load_normalization_stats(stats_filepath)
    normalized_tensors = {}

    for harp, (X_seq, X_static, X_mask) in inference_tensors.items():
        X_seq_norm = apply_normalization(X_seq, stats)
        normalized_tensors[harp] = (X_seq_norm, X_static, X_mask)

    return normalized_tensors

